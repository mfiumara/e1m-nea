"""Write docs/pinmap.md, docs/edge-pinout.md and docs/images/edge-pinout.png from the JSON data.

    python scripts/gen_docs.py       # needs pillow
"""
import json
import os
import re

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pm = json.load(open(f"{ROOT}/hardware/data/pinmap.json"))
ep = json.load(open(f"{ROOT}/hardware/data/edge_pinout.json"))
pad_of = {p["net"]: p["num"] for p in ep["pads"] if p["net"] not in ("GND", "VIN", "VREF_1V8")}


def natural(s):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", str(s))]


# ---------------------------------------------------------------- pinmap.md
L = ["# Pin allocation", "", "Generated by `scripts/gen_docs.py` from `hardware/data/pinmap.json`. Do not edit.", "",
     f"{len(pm['edge'])} edge nets and {len(pm['internal'])} on-module nets use Alif balls; "
     f"{len(pm['free_pins'])} GPIO balls are left over. Not placed: {', '.join(pm['dropped']) or 'none'}.", "",
     "## Edge nets", "", "| Edge pad | Net | Alif pin | Ball | Signal (mux) | Group |", "| --- | --- | --- | --- | --- | --- |"]
for net, e in sorted(pm["edge"].items(), key=lambda kv: (kv[1]["group"], natural(kv[0]))):
    mux = "" if e["mux"] is None else f" ({e['mux']})"
    L.append(f"| {pad_of[net]} | {net} | {e['pin']} | {e['ball']} | {e['signal']}{mux} | {e['group']} |")
L += ["", "## On-module nets", "", "| Net | Alif pin | Ball | Signal (mux) |", "| --- | --- | --- | --- |"]
for net, e in sorted(pm["internal"].items(), key=lambda kv: natural(kv[0])):
    L.append(f"| {net} | {e['pin']} | {e['ball']} | {e['signal']} ({e['mux']}) |")
open(f"{ROOT}/docs/pinmap.md", "w").write("\n".join(L) + "\n")

# ---------------------------------------------------------------- edge-pinout.md
CAT = [("power", ("VIN", "VREF_1V8", "SD_VDD")), ("gnd", ("GND",)),
       ("control", ("EN", "STBY_N", "RESET_N", "WAKE_N", "DBG_NRST")),
       ("debug", ("CONSOLE_", "SWDIO", "SWCLK", "SWO", "TDI", "WIFI_")),
       ("hs", ("CSI_", "DSI_", "USB_", "ETH_TX", "ETH_RX")), ("rf", ("ANT",)),
       ("analog", ("AIN", "AOUT")), ("gpio", ("GPIO",))]
COL = {"power": (214, 62, 62), "gnd": (60, 60, 60), "control": (230, 140, 30), "debug": (150, 90, 200),
       "hs": (40, 120, 220), "rf": (220, 30, 140), "analog": (40, 170, 120), "gpio": (120, 120, 120),
       "io": (90, 150, 60)}


def cat(net):
    for c, pre in CAT:
        if net == "GND" and c == "gnd":
            return c
        if net != "GND" and net.startswith(pre):
            return c
    return "io"


L = ["# Edge pinout", "", "Generated by `scripts/gen_docs.py` from `hardware/data/edge_pinout.json` "
     "(`scripts/gen_edge.py`). Do not edit.", "",
     "This is the Fiumara Labs AE3 SoM's own edge pinout: a 35 × 35 mm LGA module with 244 round 0.60 mm "
     "pads at 1.0 mm pitch in two rings, numbered anticlockwise from the top of the left side (outer ring "
     "1–124, inner ring 125–244).", "", "![Edge pinout, top view](images/edge-pinout.png)", "",
     "## Non-SoC nets", "", "| Net | Pads | Connection |", "| --- | --- | --- |"]
for net, desc in ep["other"].items():
    nums = ", ".join(str(p["num"]) for p in ep["pads"] if p["net"] == net)
    L.append(f"| {net} | {nums} | {desc} |")
L += ["", "## All pads", "", "| Pad | x, y (mm) | Ring | Net |", "| --- | --- | --- | --- |"]
for p in ep["pads"]:
    L.append(f"| {p['num']} | {p['x']}, {p['y']} | {p['ring']} | {p['net']} |")
open(f"{ROOT}/docs/edge-pinout.md", "w").write("\n".join(L) + "\n")

# ---------------------------------------------------------------- edge-pinout.png (top view)
S = 64                      # px per mm
W = int(35 * S) + 2 * 260
img = Image.new("RGB", (W, W), "white")
d = ImageDraw.Draw(img)
off = W / 2
try:
    font = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial Narrow.ttf", 17)
    big = ImageFont.truetype("/System/Library/Fonts/Supplemental/Arial Bold.ttf", 34)
except OSError:
    font = big = ImageFont.load_default()
d.rectangle((off - 17.5 * S, off - 17.5 * S, off + 17.5 * S, off + 17.5 * S), outline=(0, 0, 0), width=4)
d.polygon([(off - 17.5 * S, off - 17.5 * S), (off - 16.8 * S, off - 17.5 * S), (off - 17.5 * S, off - 16.8 * S)],
          fill=(0, 0, 0))
for p in ep["pads"]:
    cx, cy = off + p["x"] * S, off + p["y"] * S
    r = 0.3 * S
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=COL[cat(p["net"])])
    if p["net"] == "GND":
        continue
    w = int(d.textlength(p["net"], font=font)) + 2
    t = Image.new("RGBA", (w, 22), (0, 0, 0, 0))
    ImageDraw.Draw(t).text((0, 1), p["net"], font=font, fill=(0, 0, 0))
    # outer-ring labels go outside the module outline, inner-ring labels towards the centre
    outward = p["ring"] == "outer"
    g = 1.65 * S if outward else 0.42 * S
    if p["side"] in ("left", "right"):
        to_left = (p["side"] == "left") == outward
        x0 = cx - g - w if to_left else cx + g
        img.paste(t, (int(x0), int(cy - 11)), t)
    else:
        rt = t.rotate(90, expand=True)          # reads bottom to top, size 22 x w
        up = (p["side"] == "top") == outward
        y0 = cy - g - w if up else cy + g
        img.paste(rt, (int(cx - 11), int(y0)), rt)
d.text((off - 330, off - 60), "AE3 SoM edge, top view", font=big, fill=(0, 0, 0))
d.text((off - 330, off - 10), "244 pads, 1.0 mm pitch, outer ring 1-124, inner 125-244", font=font, fill=(0, 0, 0))
y = off + 40
for c, colour in COL.items():
    d.ellipse((off - 330, y, off - 310, y + 20), fill=colour)
    d.text((off - 300, y), {"hs": "high-speed pair", "rf": "RF", "io": "digital I/O"}.get(c, c), font=font, fill=(0, 0, 0))
    y += 28
os.makedirs(f"{ROOT}/docs/images", exist_ok=True)
img.save(f"{ROOT}/docs/images/edge-pinout.png")
print("docs written")
